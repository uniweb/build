// The directory a site keeps its translations in — `site.yml`'s `i18n.localesDir`, else `locales`,
// the rule the build and `uniweb i18n` read it by — for the push and the pull alike. `subdir` scopes a
// lane: '' → site-content (locales/), 'records' → record translations (locales/records/), matching the
// i18n manifest layout.
// ⛔ It was `locales/` whatever the site said until 2026-09-26: a site keeping its translations in
// `translations/` pushed its source language alone, and a pull wrote into a directory it never read.
export function localesDir(siteRoot, subdir = '') {
  const base = join(siteRoot, localesDirName(siteRoot))
  return subdir ? join(base, subdir) : base
}

// `i18n.localesDir`, read once per version of the file — every translation a pull writes asks for it.
const localesDirCache = new Map() // siteRoot → { mtimeMs, name }
function localesDirName(siteRoot) {
  const file = join(siteRoot, 'site.yml')
  let mtimeMs = null
  try {
    mtimeMs = statSync(file).mtimeMs
  } catch {
    return 'locales'
  }
  const cached = localesDirCache.get(siteRoot)
  if (cached && cached.mtimeMs === mtimeMs) return cached.name
  let name = 'locales'
  try {
    const dir = yaml.load(readFileSync(file, 'utf8'), YAML_OPTIONS)?.i18n?.localesDir
    if (typeof dir === 'string' && dir.trim()) name = dir.trim()
  } catch {
    // unreadable — the default
  }
  localesDirCache.set(siteRoot, { mtimeMs, name })
  return name
}

export function localeFilePath(siteRoot, locale, subdir = '') {
  return join(localesDir(siteRoot, subdir), `${locale}.json`)
}

// True for a `{ <lang>: value }` localized map (vs a bare scalar / array / null).
export function isLocalizedMap(value) {
  return value != null && typeof value === 'object' && !Array.isArray(value)
}

/**
 * Read `locales/{locale}.json` for each target locale into `{ locale: { hash: tgt } }`.
 * The producer's counterpart to writeLocaleTranslations — used to wrap source values
 * back into per-locale form on push. Missing / unreadable files are skipped.
 */
/**
 * Discover the target locales present on disk for a lane — the `{locale}.json`
 * files in `locales/[subdir]/` (excluding the derived `manifest.json` and dotfiles).
 * Lets the producer wrap exactly the locales that have translation files, without
 * re-reading the site's declared language list (a declared-but-empty locale has
 * nothing to wrap anyway).
 */
export function discoverLocales(siteRoot, subdir = '') {
  const dir = localesDir(siteRoot, subdir)
  if (!existsSync(dir)) return []
  try {
    return readdirSync(dir)
      .filter((f) => f.endsWith('.json') && !RESERVED_LOCALE_FILES.has(f) && !f.startsWith('.'))
      .map((f) => f.slice(0, -'.json'.length))
  } catch {
    return []
  }
}

// Locales that have a free-form override directory (`locales/freeform/{locale}/`),
// across all lanes. A section or collection record may be localized ONLY by a
// free-form body, with no structural-translation `{locale}.json` to discover it
// from — so the collections producer unions these with discoverLocales.
export function discoverFreeformLocales(siteRoot) {
  const dir = join(localesDir(siteRoot), 'freeform')
  if (!existsSync(dir)) return []
  try {
    return readdirSync(dir, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
  } catch {
    return []
  }
}

export function loadLocaleTranslations(siteRoot, locales, subdir = '') {
  const out = {}
  for (const locale of locales || []) {
    const filePath = localeFilePath(siteRoot, locale, subdir)
    if (!existsSync(filePath)) continue
    try {
      const parsed = JSON.parse(readFileSync(filePath, 'utf8'))
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) out[locale] = parsed
    } catch {
      // unreadable / invalid → skip
    }
  }
  return out
}

/**
 * ⭐ WHAT A PULL KEEPS FOR A PUSH TO SEND BACK, `locales/_kept.json`: for a section, its `@` (what the
 * app holds beside its translations, opaque here) and its documents in languages the site does not
 * list (a language removed in the app keeps them, so adding it back loses nothing). A file has no
 * other place for either, and THE ROUND-TRIP LAW holds for both. Absent on almost every site.
 *
 * ⛔ Until 2026-10-31 a pull dropped both, and the next push of the section removed them from the store.
 *
 * Keyed as a translation's place is (`contextKey`), since a section's identity on a backend is no use
 * to another backend's copy.
 *
 * @param {string} siteRoot
 * @param {string} [subdir] - `records` for record translations
 * @returns {{ [place: string]: { '@'?: object, languages?: object } }}
 */
export function readKept(siteRoot, subdir = '') {
  try {
    const parsed = JSON.parse(readFileSync(join(localesDir(siteRoot, subdir), KEPT_FILE), 'utf8'))
    return parsed && typeof parsed === 'object' && !Array.isArray(parsed) ? parsed : {}
  } catch {
    return {}
  }
}

/** Where a record's localized field is kept: a record has more than one such field. */
export function recordFieldPlace(context, field) {
  return `${contextKey(context)}#${field}`
}

/** A localized `content` with what the site keeps for it: never over a language the push has now. */
export function restoreKept(localized, held) {
  if (!held || !isLocalizedContent(localized)) return localized
  const out = { ...localized }
  for (const [locale, doc] of Object.entries(held.languages || {})) {
    if (!(locale in out)) out[locale] = doc
  }
  if (held['@']) out['@'] = held['@']
  return out
}

/**
 * Write what a pull read to `locales/_kept.json`, removing the file when nothing is kept. An entry
 * keeps its place and the pull adds nothing it did not change, as `writeLocaleTranslations` does.
 *
 * @param {string} siteRoot
 * @param {object} kept - the collector's `kept`
 * @param {string} [subdir]
 * @param {Set<string>|null} [read] - the places this pull read, and only these change. None: every
 *   place is the document's to say, for a lane whose document is the whole site.
 * @returns {'updated'|'unchanged'}
 */
export function writeKept(siteRoot, kept, subdir = '', read = null) {
  const filePath = join(localesDir(siteRoot, subdir), KEPT_FILE)
  let text = null
  try {
    text = readFileSync(filePath, 'utf8')
  } catch {
    // absent
  }
  const existing = text ? readKept(siteRoot, subdir) : {}
  const order = text ? topLevelKeyOrder(text).filter((key) => key in existing) : []
  const entries = []
  for (const key of order) {
    if (key in kept) entries.push([key, canonicalJson(kept[key]) === canonicalJson(existing[key]) ? existing[key] : kept[key]])
    else if (read && !read.has(key)) entries.push([key, existing[key]])
  }
  for (const key of Object.keys(kept).filter((k) => !order.includes(k)).sort()) entries.push([key, kept[key]])
  if (entries.length === 0) {
    if (text === null) return 'unchanged'
    rmSync(filePath)
    return 'updated'
  }
  const next = jsonObjectText(entries)
  if (next === text) return 'unchanged'
  mkdirSync(dirname(filePath), { recursive: true })
  writeFileSync(filePath, next)
  return 'updated'
}

/**
 * Wrap a section's source-locale content DOC into its localized `content` form: the
 * source locale stays the doc, and EACH TARGET LOCALE BECOMES A SELF-CONTAINED DOC
 * (not a structural map) — resolved from the doc's source structure joined with
 * `locales/{locale}.json` via the merge resolver. A self-contained doc is the
 * portable, renderer-ready form — a source-keyed map is an authoring representation
 * that must be resolved against the source before it can be rendered; the structural
 * map lives only on disk (`locales/{locale}.json`) and is recovered on pull (see
 * unwrapLocalizedContent).
 *
 * ALWAYS returns the per-locale map — `{ [sourceLocale]: doc }` at minimum. A target
 * locale with no translation for THIS doc is omitted (it falls back to the source
 * locale through the delivery locale chain), so the payload stays lean.
 *
 * It used to return the bare doc when nothing had been translated, which made the
 * wire shape depend on *whether a given section happened to have a translation* —
 * so one push could carry a map for a translated section and a bare doc for its
 * untranslated neighbour, on the same page. The field declares `localized: true`,
 * and a bare doc makes that declaration false: `{type, content}` is an object, so
 * it satisfies "must be a map" with `type` and `content` sitting where locale codes
 * belong, and a store cannot validate the one property the field declares. Every
 * reader then has to disambiguate by asking "does this object happen to look like a
 * ProseMirror doc" — a heuristic that has to be implemented identically in three
 * codebases forever, and has already fail-opened in one of them.
 *
 * `localizeScalar` below has always wrapped unconditionally, so the producer was
 * also inconsistent with itself: a section's `title` shipped as `{en: …}` while its
 * `content` shipped bare, in the same payload.
 *
 * Readers stay tolerant of the bare form permanently — it exists in stores, in
 * `.uwx` files on disk, and in every backup taken before this change. This changes
 * what we WRITE, never what we accept (see `isLocalizedContent`, and
 * `unwrapLocalizedContent`, which returns `content[sourceLocale]` so a source-only
 * map round-trips back to a bare doc on the file lane).
 *
 * @param {object} doc - the source-locale ProseMirror content doc
 * @param {string} sourceLocale
 * @param {string[]} [targetLocales]
 * @param {object} [translations] - `{ locale: { hash: tgt } }` from loadLocaleTranslations
 * @param {object} [context] - the section's translation context
 * @param {(tag: string) => object|null} [modelFor] - the section's data-block models by tag
 *   (`i18n/data-models.js`), so a block is translated as the build translates it
 */
export function localizeContentDoc(doc, sourceLocale, targetLocales, translations, context = undefined, modelFor = () => null) {
  // Non-docs (null, an already-localized map) pass through untouched.
  if (!isProseMirrorDoc(doc)) return doc

  const result = { [sourceLocale]: doc }
  if (targetLocales && translations) {
    for (const locale of targetLocales) {
      const table = translations[locale]
      if (!table) continue
      // With the section's context, so a context-specific override resolves as the build resolves it.
      const resolved = resolveDocForLocale(doc, table, context, modelFor)
      if (resolved) result[locale] = resolved
    }
  }
  return result
}

/**
 * Wrap a SCALAR field value into its localized `{ <lang>: value }` form: the source
 * locale plus any target locales whose `locales/{locale}.json` carries a translation
 * for this exact source text (`hash(value)`). The inverse of the projector's scalar
 * collector. An already-localized object passes through; null/undefined → undefined.
 *
 * @param {*} value
 * @param {string} sourceLocale
 * @param {object} [translations] - `{ locale: { hash: tgt } }` from loadLocaleTranslations
 */
export function localizeScalar(value, sourceLocale, translations, context = null) {
  if (value == null) return undefined
  if (typeof value === 'object') return value // already a { lang: value } map
  const out = { [sourceLocale]: value }
  if (translations && typeof value === 'string') {
    const hash = computeHash(value)
    for (const [locale, table] of Object.entries(translations)) {
      const tgt = translationFor(table?.[hash], context)
      if (typeof tgt === 'string') out[locale] = tgt
    }
  }
  return out
}

/**
 * A translation entry's text in one place: a string as it is; `{ default, overrides }` — a
 * string that reads differently in some places — by the place's key (`contextKey`), else its
 * default. ⛔ Until 2026-09-26 a scalar's entry in that form was dropped whole, its default too:
 * the build rendered it, and a push carried the source alone.
 *
 * @param {*} entry - a translation file's entry
 * @param {{ key?: string, page?: string, section?: string }|null} context - where the value is
 * @returns {string|undefined}
 */
export function translationFor(entry, context) {
  if (typeof entry === 'string') return entry
  if (!entry || typeof entry !== 'object') return undefined
  const override = context ? entry.overrides?.[contextKey(context)] : undefined
  return typeof override === 'string' ? override : typeof entry.default === 'string' ? entry.default : undefined
}

/**
 * The key an override names a place by: a record's identity (`<pool>/<handle>`, as `key`), or
 * a page section's `<route>:<id>` (`i18n/extract.js::translationContext`) — as `i18n/merge.js`
 * reads it.
 */
export function contextKey(context) {
  return context?.key ?? `${context?.page}:${context?.section}`
}

/**
 * A localized PLAIN-TEXT value — a page's title, label, description, keywords and Open Graph
 * texts, and the site's — with each translation as text, as the build renders it
 * (`i18n/merge.js::toPlainText`). The source stays as the author wrote it, as the build leaves it.
 * ⛔ Until 2026-10-16 a push sent a translation's markdown as it was, so a unit shared by a page's
 * title and a link to the page reached a host as `[Sign in](/sign-in)`.
 *
 * @param {object|Array|undefined} value - a `{ locale: text }` map, or a list of them
 * @param {string} sourceLocale
 */
export function plainTextTargets(value, sourceLocale) {
  if (Array.isArray(value)) return value.map((item) => plainTextTargets(item, sourceLocale))
  if (!value || typeof value !== 'object') return value
  let out = value
  for (const [locale, text] of Object.entries(value)) {
    if (locale === sourceLocale || typeof text !== 'string') continue
    const plain = toPlainText(text)
    if (plain === text) continue
    if (out === value) out = { ...value }
    out[locale] = plain
  }
  return out
}

/**
 * Wrap a `multiple: true` + `localized: true` field (e.g. page `keywords` — "array
 * of localized strings") into per-locale form by localizing each element. Container
 * shape is preserved so the round-trip is a fixed point: an array authored as an
 * array stays an array of `{ <lang>: value }` maps; a bare scalar (the degenerate
 * single-value authoring) wraps as one localized scalar. null/undefined → undefined.
 *
 * @param {*} value
 * @param {string} sourceLocale
 * @param {object} [translations] - `{ locale: { hash: tgt } }` from loadLocaleTranslations
 */
export function localizeScalarList(value, sourceLocale, translations, context = null) {
  if (value == null) return undefined
  if (!Array.isArray(value)) return localizeScalar(value, sourceLocale, translations, context)
  return value.map((item) => localizeScalar(item, sourceLocale, translations, context))
}

// True for a ProseMirror document node (`{ type: 'doc', content: [...] }`).
export function isProseMirrorDoc(value) {
  return value != null && typeof value === 'object' && value.type === 'doc'
}

// A localized `content` field carries one value per locale: the SOURCE locale is a
// ProseMirror doc, a TARGET locale is either a structural `{ src-text: target }`
// map (the default) or a full doc (free-form override). A bare doc (no locale wrap)
// is the source-only / pre-localization shape — left as-is.
export function isLocalizedContent(value) {
  return isLocalizedMap(value) && !isProseMirrorDoc(value)
}

/**
 * Accumulate target-locale translations for localized SCALAR fields across a
 * projection, then flush them to `locales/{locale}.json`. The source-locale value
 * is written inline by the caller (page.yml / site.yml); this captures the rest.
 *
 * `add(localizedValue)` records, for each non-source locale, `hash(source) → target`
 * (source text hashed exactly as `i18n extract` keys it). Non-string or missing
 * values are skipped (only hashable scalars belong in the hash manifest).
 *
 * With `languages` (`documentLanguages`), a value in any other language is left out of the
 * translation files, and the language is named in `outside` for the caller to report. A whole document
 * in one is kept (`keepLanguage`, `readKept`), so a push sends it back.
 */
export function createTranslationCollector(sourceLocale, { siteRoot = null, languages = null } = {}) {
  const byLocale = {} // { locale: { hash: target } }
  const outside = new Set() // the languages read that the site does not have
  const kept = {} // { place: { '@'?, languages? } }, what `readKept` gives back
  const keptRead = new Set() // the places read, whether or not they keep anything
  const marks = { cleared: {}, outdated: {} } // what `addStructuralMap` was told of each row beyond its value

  function keepMeta(place, at) {
    keptRead.add(place)
    if (at && typeof at === 'object' && Object.keys(at).length > 0) (kept[place] ||= {})['@'] = at
  }

  function keepLanguage(place, locale, doc) {
    if (isProseMirrorDoc(doc)) ((kept[place] ||= {}).languages ||= {})[locale] = doc
  }

  function has(locale) {
    if (!languages || languages.includes(locale)) return true
    outside.add(locale)
    return false
  }
  // ⭐ What says each value read, in the place it was read — the push's own rule there — so the
  // writer keeps an author's entry that says the same thing in another spelling (`reconcileTranslation`).
  const says = {} // { locale: { hash: { plain?: (value) => boolean, values: { [contextKey]: (value) => boolean } } } }
  const freeformPending = [] // [{ locale, content }] — target-locale free-form bodies

  function noteSays(locale, hash, context, check) {
    const entry = ((says[locale] ||= {})[hash] ||= { plain: undefined, values: {} })
    if (context) entry.values[contextKey(context)] = check
    else entry.plain = check
  }

  // Record a localized SCALAR field's target locales (hash of the source scalar). ⭐ With `context`
  // — the record it was read in (`{ key: '<pool>/<handle>' }`) — a translation that differs from one
  // record to another comes back as the author's `{ default, overrides }`, as a page section's does.
  // ⭐ `plainText` for a field the push sends as text (`plainTextTargets`): any value with those words
  // says it.
  function add(localizedValue, context = null, { plainText = false } = {}) {
    if (!isLocalizedMap(localizedValue)) return
    const source = localizedValue[sourceLocale]
    if (typeof source !== 'string' || source.length === 0) return
    const hash = computeHash(source)
    for (const [locale, value] of Object.entries(localizedValue)) {
      if (locale === sourceLocale) continue
      if (typeof value !== 'string' || !has(locale)) continue
      const table = (byLocale[locale] ||= {})
      noteSays(locale, hash, context, plainText ? saysAsText(value) : saysAsIs(value))
      if (!context) {
        if (table[hash] instanceof SeenInContexts) table[hash].plain = value
        else table[hash] = value
        continue
      }
      const seen = table[hash] instanceof SeenInContexts ? table[hash] : new SeenInContexts(table[hash])
      seen.values[contextKey(context)] = value
      table[hash] = seen
    }
  }

  // Record a structural translation MAP for one target locale: `{ src-text: target }`
  // keyed by the source text exactly as `i18n extract` keys it (hash of the source).
  // ⭐ With `context` — where the map was read (`translationContext`) — a translation that differs
  // from one section to another is kept per section, and comes back as the author's
  // context-specific overrides (`writeLocaleTranslations`). ⛔ Until 2026-09-26 the last section
  // read won, and a pull wrote that one string over the author's `{ default, overrides }`.
  // `checks` — what says each element's translation (`deriveStructuralMap`); a value as read, else.
  // `notes` — its rows that hold their source, and those that hold an older source's translation.
  function addStructuralMap(locale, map, context = null, checks = null, notes = null) {
    if (locale === sourceLocale || !map || typeof map !== 'object' || Array.isArray(map) || !has(locale)) return
    const place = context ? contextKey(context) : ''
    for (const [src, row] of Object.entries(notes?.cleared || {})) {
      ;((marks.cleared[locale] ||= {})[computeHash(src)] ||= {})[place] = row
    }
    for (const [src, older] of Object.entries(notes?.outdated || {})) {
      ;((marks.outdated[locale] ||= {})[computeHash(src)] ||= {})[place] = older
    }
    const table = (byLocale[locale] ||= {})
    for (const [src, target] of Object.entries(map)) {
      if (typeof src !== 'string' || typeof target !== 'string') continue
      const hash = computeHash(src)
      noteSays(locale, hash, context, checks?.[src] ?? saysAsIs(target))
      if (!context) {
        if (table[hash] instanceof SeenInContexts) table[hash].plain = target
        else table[hash] = target
        continue
      }
      const seen = table[hash] instanceof SeenInContexts ? table[hash] : new SeenInContexts(table[hash])
      seen.values[contextKey(context)] = target
      table[hash] = seen
    }
  }

  // Note a target-locale FREE-FORM body (a full doc override): `target` is the
  // translated doc, `source` is the source-locale doc (for the staleness hash), and
  // `relpath` is the freeform file path (locale-independent, from buildFreeformPath)
  // — null when the caller can't place it (e.g. layout sections have no freeform
  // home), so it's surfaced rather than dropped.
  function noteFreeform(locale, target, source, relpath) {
    if (!has(locale)) return
    freeformPending.push({ locale, target, source, relpath: relpath || null })
  }

  // ⭐ The FREE-FORM file the site keeps for this translation, if any — the first of `relpaths` (the
  // order the renderer looks them up in, `freeformPathsFor`) that exists for `locale`. A pulled
  // translation goes back into that file, whatever its shape. ⛔ Until 2026-09-25 a free-form body
  // whose paragraphs lined up with its source's was read as a structural translation, and a pull into
  // the author's copy wrote its text over their `locales/{locale}.json` entries for those paragraphs —
  // measured on the `international` template's `about/story`, in Spanish and French.
  function keptFreeform(locale, relpaths) {
    if (!siteRoot) return null
    for (const rel of [].concat(relpaths || [])) {
      if (rel && existsSync(join(localesDir(siteRoot), 'freeform', locale, rel))) return rel
    }
    return null
  }

  return { add, addStructuralMap, noteFreeform, keptFreeform, keepMeta, keepLanguage, has, byLocale, says, marks, freeformPending, outside, kept, keptRead }
}

/**
 * Derive a structural `{ source-text: target-inline-markdown }` map from a
 * (source doc, target doc) pair — the inverse of resolveDocForLocale, used on pull
 * to recover the compact `locales/{locale}.json` surface from the DOC the wire now
 * carries. Returns the map when the target is structurally CONGRUENT with the
 * source (same sequence of block elements by type) so it round-trips losslessly;
 * returns null when the target diverges (the caller stores it as a free-form body
 * instead). An element whose inline markdown is identical to the source is
 * untranslated and omitted. The value is the target element's inline content as
 * inline markdown (serializeInlineContent), so emphasis, inline icons, and
 * per-locale link hrefs survive. Keyed by the source element's cleaned text, so
 * `computeHash(key)` matches the extractor's unit hash — closing the round trip.
 *
 * ⭐ `notes` hears what a value alone can't say. `cleared`: a row holding its source, so that source's
 * entry goes, and a translation an author cleared stays cleared. `outdated`: a row holding what the
 * app keeps as an older source text's translation (`olderSource`). It is still what the row reads, so
 * it stays in the map, and the caller records it as outdated rather than as this source's.
 *
 * ⭐ TWO ROWS OF ONE SOURCE TEXT THAT READ DIFFERENTLY cannot be said by one entry, so the target is
 * free-form. ⛔ Until 2026-10-31 the last one won: `(zh_A, zh_B)` became `(zh_B, zh_B)` on the next push.
 */
function deriveStructuralMap(sourceDoc, targetDoc, modelFor = () => null, checks = {}, notes = { cleared: {}, outdated: {} }, olderSource = () => null) {
  if (!isProseMirrorDoc(sourceDoc) || !isProseMirrorDoc(targetDoc)) return null
  const src = blockElements(sourceDoc)
  const tgt = blockElements(targetDoc)
  if (src.length !== tgt.length) return null // structurally divergent → free-form
  const map = {}
  const read = new Map()
  try {
    for (let i = 0; i < src.length; i++) {
      if (src[i].type !== tgt[i].type) return null // divergent → free-form
      const key = elementText(src[i])
      if (!key) continue
      const srcMd = serializeInlineContent(src[i].content || [])
      const tgtMd = serializeInlineContent(tgt[i].content || [])
      const says = srcMd === tgtMd ? null : labelsAlone(src[i].content || [], tgt[i].content || [], tgtMd) ?? tgtMd
      if (read.has(key) && read.get(key) !== says) return null // one entry cannot say both → free-form
      read.set(key, says)
      if (says === null) {
        // unchanged → untranslated → omit, and no entry says otherwise
        notes.cleared[key] = { markdown: srcMd, says: saysElement(src[i].content || [], tgtMd) }
        continue
      }
      map[key] = says
      checks[key] = saysElement(src[i].content || [], tgtMd)
      const older = olderSource(tgt[i], key)
      if (older) notes.outdated[key] = older
    }
  } catch {
    // a mark we can't serialize → don't risk a lossy map; store as free-form
    return null
  }
  const withData = addDataBlockStrings(map, sourceDoc, targetDoc, modelFor, checks)
  return withData && addImageTranslations(withData, sourceDoc, targetDoc, checks)
}

// ⭐ AN IMAGE's translation, read pairwise — what a translation may give it (`merge.js::translateImages`):
// its words alone when only its alt text changed, else the image as inline markdown (`imageMarkup`),
// never the identity a push stamps beside a URL. Keyed by its source alt text, as extraction keys it.
// A target whose images differ in anything else — their number, a role, a size — or that changed an
// image with no alt text cannot be said per image, and the whole translation is free-form.
// ⛔ Until 2026-10-28 an image was not read here, and its translation was not sent either.
function addImageTranslations(map, sourceDoc, targetDoc, checks = null) {
  const src = imageNodes(sourceDoc)
  const tgt = imageNodes(targetDoc)
  if (src.length !== tgt.length) return null
  for (let i = 0; i < src.length; i++) {
    const s = src[i].attrs || {}
    const t = tgt[i].attrs || {}
    if (canonicalJson(untranslated(s)) !== canonicalJson(untranslated(t))) return null
    const changed = TRANSLATED_IMAGE_ATTRS.filter((attr) => (s[attr] ?? null) !== (t[attr] ?? null))
    if (!changed.length) continue
    const key = typeof s.alt === 'string' ? s.alt.trim() : ''
    if (!key) return null
    const words = typeof t.alt === 'string' ? t.alt.trim() : ''
    const value = changed.every((attr) => attr === 'alt') ? words : imageMarkup(tgt[i])
    if (!value) return null
    // A text element of the same words read its own translation: the image's says them too when its
    // words match, and a text element reads an image value as its words (`merge.js::translatedInline`).
    if (map[key] !== undefined && map[key] !== value && toPlainText(map[key]).trim() !== words) return null
    map[key] = value
    if (checks) checks[key] = saysImage(s, t)
  }
  return map
}

// What a translation may not change about an image: everything but its words and files, and the
// identity a push stamps beside each URL.
const IMAGE_IDENTITY = new Set(ASSET_SLOTS.flatMap((slot) => [slot.id, slot.ext]))
function untranslated(attrs) {
  const out = {}
  for (const [key, value] of Object.entries(attrs)) {
    if (TRANSLATED_IMAGE_ATTRS.includes(key) || IMAGE_IDENTITY.has(key)) continue
    if (value != null) out[key] = value
  }
  return out
}

// Whether a value, pushed onto the source image, gives it what the pull read.
function saysImage(source, read) {
  return (value) => {
    if (typeof value !== 'string') return false
    const given = translatedImage(value)
    if (!given) return false
    return TRANSLATED_IMAGE_ATTRS.every((attr) => (given[attr] ?? source[attr] ?? null) === (read[attr] ?? null))
  }
}

// ⭐ WHAT SAYS A TRANSLATION, WHERE A PULL READ IT — the push's own rule for that place. A pull reads
// one spelling back, and an author's entry may say the same thing in another: `[Faire un don](/contact)`
// where the merge reads the label onto the source's own link, or `[Se connecter](/sign-in)` for a page
// title, which the push sends as its words.
//   - an element of a section: what `merge.js::translatedInline` makes of a value there;
//   - a plain-text field (`plainTextTargets`): a value's words;
//   - anything else: the value as read.
function saysElement(source, pushed) {
  return (value) => {
    if (typeof value !== 'string') return false
    try {
      const back = translatedInline(source, value)
      return !!back && serializeInlineContent(back) === pushed
    } catch {
      return false
    }
  }
}

function saysAsText(read) {
  return (value) => {
    if (typeof value !== 'string') return false
    try {
      return toPlainText(value) === read
    } catch {
      return false
    }
  }
}

function saysAsIs(read) {
  return (value) => value === read
}

// Whether a free-form file says `target`, read as a push reads it — its body, as stored.
function sameStoredFreeform(text, filePath, target) {
  try {
    return sameMarkdownDocument(parseFrontmatter(text, filePath).body, target)
  } catch {
    return false
  }
}

// ⭐ A LINK'S LABEL, NOT THE LINK, when only its words were translated. The merge reads a label onto
// the source's own link (`merge.js::translatedInline`), so it keeps following that link wherever the
// source moves it, where `[Donar Ahora](/contact)` would keep `/contact`. Several links are a label a
// line, as a translator writes them. Written only when the merge reads it back to this very element;
// a link a translator changed — the Spanish button pointed at a Spanish page — is written whole.
// ⛔ Until 2026-10-08 the element was always written whole: once the merge read a label (2026-10-01),
// a pull into the copy that pushed rewrote `"Donar Ahora"` as `"[Donar Ahora](/contact)"`, and split a
// string a page title and a button share into a default and per-place overrides.
function labelsAlone(source, target, whole) {
  const labels = linkLabels(source, target)
  if (!labels) return null
  const value = labels.map((nodes) => serializeInlineContent(nodes)).join('\n')
  const back = translatedInline(source, value)
  return back && serializeInlineContent(back) === whole ? value : null
}

// ⭐ A TAGGED DATA BLOCK's translated strings, read pairwise — the strings the build translates
// (`visitDataBlockStrings`: a block's declared shape, else the extractor's heuristic), keyed by their
// source text as the build keys them. ⭐ Walked by the same model the push translated with — the pairing
// is by position, so a declared text field the heuristic skips (a `status`) would otherwise read a
// faithful translation as another shape.
// A target that is not the source with only those strings changed — another shape, another `href` —
// cannot be said per string, and the whole translation is free-form. ⛔ Until 2026-09-26 a data block
// was not read here at all, and its translations were not sent (`merge.js::translateDataBlocks`).
function addDataBlockStrings(map, sourceDoc, targetDoc, modelFor = () => null, checks = null) {
  const srcBlocks = dataBlockNodes(sourceDoc)
  const tgtBlocks = dataBlockNodes(targetDoc)
  if (srcBlocks.length !== tgtBlocks.length) return null
  for (let i = 0; i < srcBlocks.length; i++) {
    const s = srcBlocks[i].attrs || {}
    const t = tgtBlocks[i].attrs || {}
    if (s.tag !== t.tag) return null
    if (!s.data || typeof s.data !== 'object') {
      if (canonicalJson(s.data) !== canonicalJson(t.data)) return null
      continue
    }
    const strings = (data) => {
      const out = []
      visitDataBlockStrings(JSON.parse(JSON.stringify(data ?? null)), (value) => void out.push(value), modelFor(s.tag))
      return out
    }
    const from = strings(s.data)
    const to = strings(t.data)
    if (from.length !== to.length) return null
    const pairs = new Map()
    for (let j = 0; j < from.length; j++) {
      if (from[j] === to[j]) continue
      if (pairs.has(from[j]) && pairs.get(from[j]) !== to[j]) return null // one string, two translations
      pairs.set(from[j], to[j])
    }
    const rebuilt = JSON.parse(JSON.stringify(s.data))
    visitDataBlockStrings(rebuilt, (value) => pairs.get(value) ?? value, modelFor(s.tag))
    if (canonicalJson(rebuilt) !== canonicalJson(t.data)) return null
    for (const [from, to] of pairs) {
      map[from.trim()] = to
      if (checks) checks[from.trim()] = saysAsIs(to)
    }
  }
  return map
}

/**
 * Unwrap a (possibly localized) `content` field to the SOURCE-locale ProseMirror
 * doc for the `.md` body, capturing target locales into `collector`. The wire now
 * carries a self-contained DOC per target locale: a target structurally congruent
 * with the source is recovered as a structural `locales/{locale}.json` map (via
 * deriveStructuralMap); a divergent target is a free-form body override → noted
 * with its freeform path (`freeformRelPath`, from buildFreeformPath). A structural
 * map still on the wire (legacy / transition) passes through unchanged. The
 * reserved `@` (and `$`-prefixed) key is opaque metadata — NEVER a locale. A bare
 * doc (no locale wrap) is returned unchanged.
 *
 * `place` names what is kept for this field (`readKept`): the translation's place, unless a record's
 * field needs its own.
 */
export function unwrapLocalizedContent(content, sourceLocale, collector, freeformRelPath, freeformCandidates = null, context = null, modelFor = () => null, place = context ? contextKey(context) : null) {
  if (!isLocalizedContent(content)) return content
  const source = content[sourceLocale]
  if (place) collector?.keepMeta?.(place, content['@'])
  for (const [locale, value] of Object.entries(content)) {
    if (locale === sourceLocale) continue
    if (locale === '@' || locale.startsWith('$')) continue // reserved metadata, not a locale
    if (collector?.has && !collector.has(locale)) {
      if (place) collector.keepLanguage(place, locale, value)
      continue
    }
    if (isProseMirrorDoc(value)) {
      // A translation the site keeps as a free-form file stays one, even when it lines up.
      const kept = collector?.keptFreeform?.(locale, freeformCandidates || freeformRelPath) || null
      const checks = {}
      const notes = { cleared: {}, outdated: {} }
      const map = kept ? null : deriveStructuralMap(source, value, modelFor, checks, notes, olderSourceOf(content['@'], locale))
      if (map) collector?.addStructuralMap?.(locale, map, context, checks, notes)
      else collector?.noteFreeform?.(locale, value, source, kept || freeformRelPath)
    } else {
      collector?.addStructuralMap?.(locale, value, context)
    }
  }
  return source
}

// ⭐ Which older source text a row's translation was made from, by what the app keeps in `@.translations`
// (`{ <source text>: { <lang>: <inline content> } }`): a row is outdated when its translation is one of
// those under another text. Compared as text, the key's own terms: a push's link addresses are not the store's.
function olderSourceOf(at, locale) {
  const held = at?.translations
  if (!held || typeof held !== 'object') return () => null
  const byText = new Map()
  for (const [older, byLocale] of Object.entries(held)) {
    const inline = byLocale?.[locale]
    if (Array.isArray(inline)) byText.set(elementText({ content: inline }), older)
  }
  return (element, key) => {
    const older = byText.get(elementText(element))
    return older !== undefined && older !== key ? older : null
  }
}

// A translation read in several sections: what each section's context says, and what a place with
// no context (a page title) says. Reconciled with the author's entry when the file is written.
class SeenInContexts {
  constructor(plain) {
    this.plain = typeof plain === 'string' ? plain : undefined
    this.values = {} // a place's key (`contextKey`) → translation
  }
}

// ⭐ A translation seen in several places comes back as the author keeps it: one string where every
// place agrees, else `{ default, overrides }` — their default and their overrides kept wherever they
// still hold. The default is what the places without an override of their own say (the most of
// them; the author's default when tied, else the first read). An override for a place this pull did
// not see is kept, and one that now says the default is dropped.
// ⭐ A value AGREES with a place when, pushed there, it says what the pull read (`check`, from the
// collector — the read value itself, where none was noted). So the author's entry is kept as written
// wherever it still says what every place read: a pull that changes nothing writes nothing.
// ⛔ Until 2026-10-17 values agreed only when spelled alike, and a pull rewrote an entry that says the
// same thing another way: `[Faire un don](/contact)` to its label, a string a heading and a link
// share into per-place overrides, a page title's `[Se connecter](/sign-in)` to its words.
function reconcileTranslation(existing, seen, check = null) {
  const own = existing && typeof existing === 'object' && existing.overrides && typeof existing.overrides === 'object' ? existing.overrides : {}
  const authoredDefault = typeof existing === 'string' ? existing : existing && typeof existing === 'object' ? existing.default : undefined
  // Each place read: its context's key (null where it has none), what it read, and what says that.
  const places = [
    ...(seen.plain !== undefined ? [[null, seen.plain, check?.plain ?? saysAsIs(seen.plain)]] : []),
    ...Object.entries(seen.values).map(([k, v]) => [k, v, check?.values?.[k] ?? saysAsIs(v)]),
  ]
  const at = (k) => (k !== null && k in own ? own[k] : authoredDefault)
  if (existing !== undefined && places.length && places.every(([k, , says]) => says(at(k)))) return existing
  // The places the default speaks for: those with no override of the author's own.
  const free = places.filter(([k]) => k === null || !(k in own))
  let def = authoredDefault
  if (free.length) {
    let most = -1
    for (const candidate of [...(authoredDefault !== undefined ? [authoredDefault] : []), ...free.map(([, read]) => read)]) {
      const agree = free.filter(([, , says]) => says(candidate)).length
      if (agree > most) [def, most] = [candidate, agree]
    }
  } else if (def === undefined) {
    def = places.find(([k]) => k !== null)?.[1]
  }
  const overrides = { ...own }
  for (const [k, read, says] of places) {
    if (k === null) continue
    if (says(def)) delete overrides[k]
    else if (!(k in own && says(own[k]))) overrides[k] = read
  }
  return Object.keys(overrides).length ? { default: def, overrides } : def
}

/**
 * Write captured target-locale FREE-FORM bodies to `locales/freeform/{locale}/<relpath>`
 * (markdown, body-only) and record the SOURCE hash of each one it writes in that locale's
 * `.manifest.json` for staleness tracking. Sync + idempotent: a body is rewritten
 * only when its markdown changes, and a manifest `recorded` date is (re)stamped only
 * when the source hash changes — so a no-op re-projection is byte-stable. Entries
 * with no `relpath` (unplaceable, e.g. a layout section) are surfaced as `skipped`.
 *
 * ⭐ A MANIFEST ENTRY SAYS WHICH SOURCE A TRANSLATION WAS MADE FROM, so it is stamped only with a
 * translation this pull writes. One the pull leaves as it is keeps the author's entry, whatever it
 * says: a translation the source has moved past stays stale. ⛔ Until 2026-10-17 every pull
 * stamped the hash of the source it brought — the stale translation came back current, and a
 * manifest recorded under another reading of an unchanged source was rewritten by a pull that
 * changed nothing.
 *
 * @returns {{ written: string[], skipped: object[] }}
 */
export function writeFreeformTranslations(siteRoot, freeformPending) {
  const report = { written: [], skipped: [] }
  if (!Array.isArray(freeformPending) || freeformPending.length === 0) return report

  const byLocale = new Map() // locale → entries[]
  for (const entry of freeformPending) {
    if (!entry?.relpath) {
      report.skipped.push(entry)
      continue
    }
    if (!byLocale.has(entry.locale)) byLocale.set(entry.locale, [])
    byLocale.get(entry.locale).push(entry)
  }

  for (const [locale, entries] of byLocale) {
    const localeDir = join(localesDir(siteRoot), 'freeform', locale)
    const manifestPath = join(localeDir, FREEFORM_MANIFEST)
    let manifest = {}
    if (existsSync(manifestPath)) {
      try {
        const parsed = JSON.parse(readFileSync(manifestPath, 'utf8'))
        if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) manifest = parsed
      } catch {
        // unreadable → start fresh
      }
    }

    let manifestChanged = false
    for (const { relpath, target, source } of entries) {
      const filePath = join(localeDir, relpath)
      const md = proseMirrorToMarkdown(target)
      const text = md.endsWith('\n') ? md : md + '\n'
      let current = null
      try {
        current = readFileSync(filePath, 'utf8')
      } catch {
        // absent
      }
      // ⭐ A file whose markdown already says this is left as the author wrote it — the writer's
      // markdown is not theirs (blank lines, line breaks), as for a section body (`writeSectionFile`).
      // Compared as a push reads it (`i18n/freeform.js::loadFreeformTranslation`). ⛔ Until 2026-10-08 the
      // file was trimmed first, so one whose last line ended in a space was rewritten by every pull.
      if (current === text || (current !== null && sameStoredFreeform(current, filePath, target))) continue
      mkdirSync(dirname(filePath), { recursive: true })
      writeFileSync(filePath, text)
      report.written.push(filePath)
      // Staleness hash of the SOURCE this translation comes with; re-stamp `recorded` only when it changes.
      const hash = computeSourceHash(source)
      const existing = manifest[relpath]
      if (!existing || existing.hash !== hash) {
        manifest[relpath] = { hash, recorded: new Date().toISOString().slice(0, 10) }
        manifestChanged = true
      }
    }

    if (manifestChanged) {
      mkdirSync(localeDir, { recursive: true })
      writeFileSync(manifestPath, manifestText(manifest))
    }
  }

  return report
}

/**
 * The keys of a JSON object's top level, in the order its text writes them.
 *
 * ⛔ NOT `Object.keys(JSON.parse(text))`: a JavaScript object puts every integer-like key
 * first, and a translation's key is a hash — `19544096` is one, as about one in fifty are.
 * Until 2026-09-26 a pull that changed one translation also moved each such entry to the top
 * of the author's file.
 *
 * @param {string} text - a JSON object
 * @returns {string[]}
 */
function topLevelKeyOrder(text) {
  const keys = []
  let depth = 0
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (c === '"') {
      let end = i + 1
      while (end < text.length && text[end] !== '"') end += text[end] === '\\' ? 2 : 1
      if (depth === 1 && /^\s*:/.test(text.slice(end + 1, end + 64))) keys.push(JSON.parse(text.slice(i, end + 1)))
      i = end
    } else if (c === '{' || c === '[') depth++
    else if (c === '}' || c === ']') depth--
  }
  return keys
}

/** `JSON.stringify(object, null, 2)` of these entries, in their order — see `topLevelKeyOrder`. */
function jsonObjectText(entries) {
  if (entries.length === 0) return '{}\n'
  const lines = entries.map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value, null, 2).replace(/\n/g, '\n  ')}`)
  return `{\n${lines.join(',\n')}\n}\n`
}

/**
 * ⭐ THE ENTRY A TRANSLATION FILE HOLDS for what a pull read of one source text, in one language.
 *
 * - What the places read, as the author keeps it (`reconcileTranslation`).
 * - `cleared`: places whose row holds its source. With nothing else read the entry goes, so a
 *   cleared translation stays cleared; beside a place that reads a translation, an override says so.
 *   ⛔ Until 2026-10-31 the entry stayed, and the next push brought the old translation back.
 * - `outdated`: places whose row holds an older source text's translation, `{ place: older text }`. It
 *   is still what they read, so the entry gives it to a build and a push, and `uniweb i18n status`
 *   lists it. ⛔ Until 2026-10-31 it read as this source's translation, and nothing could say otherwise.
 *
 * @returns {string|object|undefined} undefined: no entry
 */
function settleEntry(existing, seen, check, cleared, outdated) {
  let own = existing
  if (own && typeof own === 'object' && 'outdated' in own) {
    const { outdated: _flag, ...rest } = own
    own = rest
  }
  const rows = Object.entries(cleared || {})
  const places = rows.map(([place]) => place).filter(Boolean)
  const reads = seen instanceof SeenInContexts ? seen : seen === undefined ? new SeenInContexts() : new SeenInContexts(seen)
  // Whether the author's entry, pushed to these rows, gives them what they hold: their source. That is
  // no translation cleared, in whatever spelling it is written. `Pricing` is the label of `[Pricing](/pricing)`.
  const ownSaysThem = (value) => typeof value === 'string' && rows.every(([, row]) => row.says(value))
  let entry
  if (reads.plain !== undefined || Object.keys(reads.values).length > 0) {
    entry = reconcileTranslation(own, reads, check)
    const readsElsewhere = typeof entry === 'string' ? entry : entry?.default
    if (places.length && !ownSaysThem(readsElsewhere)) {
      const overrides = { ...(entry && typeof entry === 'object' ? entry.overrides : {}) }
      for (const [place, row] of rows) if (place) overrides[place] = row.markdown
      entry = { default: readsElsewhere, overrides }
    }
  } else if (ownSaysThem(own)) {
    entry = own
  } else if (own && typeof own === 'object') {
    // Its default and any overrides here go. An override for a place this pull did not see stays.
    const rest = Object.fromEntries(Object.entries(own.overrides || {}).filter(([place]) => !places.includes(place)))
    const defaultStays = typeof own.default === 'string' && ownSaysThem(own.default)
    entry = defaultStays || Object.keys(rest).length ? { ...(defaultStays ? { default: own.default } : {}), ...(Object.keys(rest).length ? { overrides: rest } : {}) } : undefined
  }
  if (entry === undefined) return undefined
  if (outdated && Object.keys(outdated).length) {
    entry = { ...(typeof entry === 'string' ? { default: entry } : entry), outdated }
  }
  if (entry && typeof entry === 'object' && Object.keys(entry).length === 1 && typeof entry.default === 'string') return entry.default
  return entry
}

/**
 * Merge `{ locale: { hash: target } }` into each `locales/{locale}.json`,
 * preserving existing entries (translations for strings not in this projection are
 * kept — `uniweb i18n audit --clean` removes genuine orphans). An entry keeps its place
 * in the file, and new ones follow it, sorted, so a pull that changes nothing writes
 * nothing. Creates `locales/` if absent.
 *
 * @param {string} siteRoot
 * @param {object} byLocale - the collector's `byLocale`
 * @param {string} [subdir] - `records` for record translations
 * @param {object} [says] - the collector's `says`: what says each value read, in its place
 *   (`reconcileTranslation`). Without it, a value says only itself.
 * @param {object} [marks] - the collector's `marks`: the rows that hold their source, and those
 *   that hold an older source's translation (`settleEntry`)
 * @returns {{ [locale: string]: 'updated' | 'unchanged' }}
 */
export function writeLocaleTranslations(siteRoot, byLocale, subdir = '', says = null, marks = null) {
  const report = {}
  for (const locale of new Set([...Object.keys(byLocale || {}), ...Object.keys(marks?.cleared || {})])) {
    const read = byLocale?.[locale] || {}
    const cleared = marks?.cleared?.[locale] || {}
    const outdated = marks?.outdated?.[locale] || {}
    if (Object.keys(read).length === 0 && Object.keys(cleared).length === 0) continue
    const filePath = localeFilePath(siteRoot, locale, subdir)

    let existing = {}
    let order = []
    if (existsSync(filePath)) {
      try {
        const text = readFileSync(filePath, 'utf8')
        const parsed = JSON.parse(text)
        if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) {
          existing = parsed
          order = topLevelKeyOrder(text).filter((key) => key in parsed)
        }
      } catch {
        // unreadable / invalid → start fresh
      }
    }

    // ⭐ A FILE THE PULL ADDS NOTHING TO IS LEFT AS IT IS, and one it does keeps its order: an entry
    // changes in its place, and new ones follow, sorted. ⛔ Until 2026-09-26 every pull re-sorted the
    // whole file by hash — measured on the `international` template, whose `es.json` runs in page
    // order: a pull that changed no translation rewrote all 77 lines.
    // A translation read in several sections becomes the string or the `{ default, overrides }` the
    // author keeps (`reconcileTranslation`) — and one read in one place too, which keeps an entry
    // that says it in another spelling, and an override for a place the pull did not see.
    const entries = {}
    for (const key of new Set([...Object.keys(read), ...Object.keys(cleared)])) {
      // Nothing to say of a row that holds its source where the file has no entry for it, and no place reads one.
      if (!(key in read) && !(key in existing)) continue
      entries[key] = settleEntry(existing[key], read[key], says?.[locale]?.[key], cleared[key], outdated[key])
    }
    const fresh = Object.keys(entries).filter((key) => !(key in existing) && entries[key] !== undefined).sort()
    const same = (key) => (entries[key] === undefined ? !(key in existing) : canonicalJson(existing[key]) === canonicalJson(entries[key]))
    if (fresh.length === 0 && Object.keys(entries).every(same)) {
      if (existsSync(filePath)) report[locale] = 'unchanged'
      continue
    }
    // An entry the pull did not change keeps its value as written — key order included.
    const merged = [...new Set([...order, ...Object.keys(existing)])]
      .filter((key) => !(key in entries) || entries[key] !== undefined)
      .map((key) => [key, key in entries && canonicalJson(entries[key]) !== canonicalJson(existing[key]) ? entries[key] : existing[key]])
    for (const key of fresh) merged.push([key, entries[key]])
    const next = jsonObjectText(merged)

    let current = null
    try {
      current = readFileSync(filePath, 'utf8')
    } catch {
      // absent
    }
    if (current === next) {
      report[locale] = 'unchanged'
      continue
    }
    mkdirSync(dirname(filePath), { recursive: true })
    writeFileSync(filePath, next)
    report[locale] = 'updated'
  }
  return report
}
